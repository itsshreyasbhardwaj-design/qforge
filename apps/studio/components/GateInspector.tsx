'use client';

import { useMemo } from 'react';
import type { IrModule } from '@qforge/compiler';
import { explainStep, type StepFact } from '../lib/explain';
import { complexText, percent } from '../lib/format';
import type { TraceView } from '../lib/useSimulation';

export interface GateInspectorProps {
  readonly module: IrModule | undefined;
  readonly trace: TraceView | undefined;
  readonly stepIndex: number;
}

const FACT_COLOUR: Record<StepFact['kind'], string> = {
  deterministic: 'var(--color-success)',
  probability: 'var(--color-accent)',
  structure: 'var(--color-phase)',
  measurement: 'var(--color-warning)',
};

/** 2x2 matrix, rendered with real brackets rather than a table border. */
function MatrixView({
  matrix,
  caption,
}: {
  matrix: readonly [unknown, unknown, unknown, unknown];
  caption?: string;
}) {
  const entries = matrix as readonly { re: number; im: number }[];
  return (
    <div>
      <div style={{ display: 'flex', alignItems: 'stretch', gap: 4 }}>
        <div
          style={{
            width: 6,
            borderLeft: '1.5px solid var(--color-text-muted)',
            borderTop: '1.5px solid var(--color-text-muted)',
            borderBottom: '1.5px solid var(--color-text-muted)',
          }}
        />
        <div
          className="qf-mono"
          style={{
            display: 'grid',
            gridTemplateColumns: 'repeat(2, minmax(0, 1fr))',
            gap: '2px 14px',
            padding: '4px 2px',
            fontVariantNumeric: 'tabular-nums',
            fontSize: 12,
          }}
        >
          {entries.map((entry, i) => (
            <span key={i} style={{ textAlign: 'right', whiteSpace: 'nowrap' }}>
              {complexText(entry.re, entry.im)}
            </span>
          ))}
        </div>
        <div
          style={{
            width: 6,
            borderRight: '1.5px solid var(--color-text-muted)',
            borderTop: '1.5px solid var(--color-text-muted)',
            borderBottom: '1.5px solid var(--color-text-muted)',
          }}
        />
      </div>
      {caption ? (
        <div style={{ fontSize: 11, color: 'var(--color-text-faint)', marginTop: 4 }}>
          {caption}
        </div>
      ) : null}
    </div>
  );
}

/**
 * Everything the simulator can say about the selected step.
 *
 * The observations under "What this did" are *computed* from the states either
 * side of the instruction — not looked up from a table of what each gate
 * usually does, and not generated by a language model. A plausible but wrong
 * explanation of a quantum circuit is worse than none, because a learner has no
 * way to tell the difference. Where a claim cannot be computed from the
 * numbers on screen, it is not made.
 */
export function GateInspector({ module, trace, stepIndex }: GateInspectorProps) {
  const explanation = useMemo(() => {
    if (!module || !trace || stepIndex < 0) return undefined;
    const step = trace.steps[stepIndex];
    const instruction = module.instructions[stepIndex];
    if (!step || !instruction) return undefined;
    const before = stepIndex === 0 ? trace.initialState : trace.steps[stepIndex - 1]?.state;
    return explainStep(
      instruction,
      module,
      before,
      step.state,
      step.measurement,
      step.conditionHeld,
    );
  }, [module, trace, stepIndex]);

  if (!module || !trace) {
    return <div className="qf-empty">Compile a program to inspect its gates.</div>;
  }
  if (stepIndex < 0) {
    return (
      <div className="qf-empty">
        Step forward, or click a gate in the circuit, to see exactly what it did to the state.
      </div>
    );
  }
  if (!explanation) {
    return <div className="qf-empty">No information for this step.</div>;
  }

  return (
    <div style={{ display: 'grid', gap: 14, padding: '10px 12px' }}>
      <div>
        <div className="qf-mono" style={{ fontSize: 14, color: 'var(--color-accent)' }}>
          {explanation.headline}
        </div>
        {explanation.description ? (
          <div style={{ fontSize: 12.5, color: 'var(--color-text-muted)', marginTop: 3 }}>
            {explanation.description}
          </div>
        ) : null}
      </div>

      <div>
        <div className="qf-label">Operands</div>
        <div style={{ display: 'grid', gap: 2, fontSize: 12.5 }}>
          {explanation.operands.map((operand, i) => (
            <div key={i} style={{ display: 'flex', justifyContent: 'space-between' }}>
              <span style={{ color: 'var(--color-text-faint)' }}>{operand.role}</span>
              <span className="qf-mono">{operand.label}</span>
            </div>
          ))}
        </div>
      </div>

      {explanation.matrix ? (
        <div>
          <div className="qf-label">Matrix</div>
          <MatrixView matrix={explanation.matrix} caption={explanation.matrixCaption} />
        </div>
      ) : (
        <div>
          <div className="qf-label">Matrix</div>
          <div style={{ fontSize: 12, color: 'var(--color-text-faint)' }}>
            {/* Honest about why: these are implemented as permutations, and a
                2^n x 2^n matrix is not a useful thing to put on screen. */}
            Shown for single-qubit gates only. Multi-qubit gates act on the whole register, and
            QForge implements them as permutations rather than as a matrix.
          </div>
        </div>
      )}

      <div>
        <div className="qf-label">
          Amplitudes this step changed ({explanation.changes.length})
        </div>
        {explanation.changes.length === 0 ? (
          <div style={{ fontSize: 12, color: 'var(--color-text-faint)' }}>
            None: the state is unchanged.
          </div>
        ) : (
          <table className="qf-table" style={{ fontSize: 11.5 }}>
            <thead>
              <tr>
                <th scope="col">Basis</th>
                <th scope="col">Before</th>
                <th scope="col">After</th>
                <th scope="col" style={{ textAlign: 'right' }}>
                  P before
                </th>
                <th scope="col" style={{ textAlign: 'right' }}>
                  P after
                </th>
              </tr>
            </thead>
            <tbody>
              {explanation.changes.slice(0, 16).map((change) => (
                <tr key={change.index}>
                  <td>{change.label}</td>
                  <td>{complexText(change.before.re, change.before.im)}</td>
                  <td style={{ color: 'var(--color-accent)' }}>
                    {complexText(change.after.re, change.after.im)}
                  </td>
                  <td data-numeric="">{percent(change.probabilityBefore)}</td>
                  <td data-numeric="">{percent(change.probabilityAfter)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        {explanation.changes.length > 16 ? (
          <div style={{ fontSize: 11, color: 'var(--color-text-faint)', marginTop: 4 }}>
            Showing 16 of {explanation.changes.length}.
          </div>
        ) : null}
      </div>

      {explanation.facts.length > 0 ? (
        <div>
          <div className="qf-label">What this did</div>
          <ul style={{ margin: 0, paddingLeft: 16, display: 'grid', gap: 5 }}>
            {explanation.facts.map((fact, i) => (
              <li
                key={i}
                style={{ fontSize: 12.5, color: 'var(--color-text)', lineHeight: 1.5 }}
              >
                <span style={{ color: FACT_COLOUR[fact.kind] }}>&#9656;</span> {fact.text}
              </li>
            ))}
          </ul>
          <div style={{ fontSize: 11, color: 'var(--color-text-faint)', marginTop: 8 }}>
            Every statement above is computed from the amplitudes in this panel. Nothing here is
            a stored description or generated text.
          </div>
        </div>
      ) : null}

      {explanation.entanglement.length > 0 ? (
        <div>
          <div className="qf-label">Per-qubit purity after this step</div>
          <table className="qf-table" style={{ fontSize: 11.5 }}>
            <thead>
              <tr>
                <th scope="col">Qubit</th>
                <th scope="col" style={{ textAlign: 'right' }}>
                  |r|
                </th>
                <th scope="col">State of its own?</th>
              </tr>
            </thead>
            <tbody>
              {explanation.entanglement.map((entry) => (
                <tr key={entry.qubit}>
                  <td>{entry.label}</td>
                  <td data-numeric="">{entry.purityLength.toFixed(4)}</td>
                  <td
                    style={{
                      color: entry.entangled ? 'var(--color-phase)' : 'var(--color-success)',
                    }}
                  >
                    {entry.entangled
                      ? entry.purityLength < 1e-9
                        ? 'no, maximally mixed'
                        : 'no, mixed'
                      : 'yes, pure'}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      ) : null}
    </div>
  );
}
