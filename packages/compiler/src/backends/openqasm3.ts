import { GATES } from '@qforge/language';
import { Opcode, resolveRegister, type IrModule, type IrRegister } from '../ir/ir.js';
import { formatAngle } from './angle.js';

/**
 * OpenQASM 3 code generator.
 *
 * Scope, stated plainly: this backend emits the *subset of OpenQASM 3 that
 * QForge programs can express* — qubit and bit declarations, the seventeen
 * gates of `stdgates.inc` that QForge exposes, `measure`, `reset` and
 * `barrier`. It is not an OpenQASM 3 implementation: there is no support for
 * classical control flow, `gate` definitions, `def` subroutines, timing, pulse
 * level constructs, aliasing, or the classical type system. See
 * docs/limitations.md for the full list.
 *
 * Output is deterministic: the same module always produces byte-identical
 * source. Nothing time- or environment-dependent is emitted, which is what
 * lets the conformance tests compare against golden files.
 */

/**
 * OpenQASM 3 reserved words. A QForge identifier that collides with one is
 * emitted with an underscore prefix, and the renaming is recorded in a comment
 * so the generated file stays self-explanatory.
 */
const QASM_RESERVED: ReadonlySet<string> = new Set([
  'OPENQASM',
  'include',
  'defcalgrammar',
  'def',
  'defcal',
  'gate',
  'extern',
  'box',
  'let',
  'break',
  'continue',
  'if',
  'else',
  'end',
  'return',
  'for',
  'while',
  'in',
  'switch',
  'case',
  'default',
  'pragma',
  'input',
  'output',
  'const',
  'readonly',
  'mutable',
  'qreg',
  'qubit',
  'creg',
  'bool',
  'bit',
  'int',
  'uint',
  'float',
  'angle',
  'complex',
  'array',
  'void',
  'duration',
  'stretch',
  'gphase',
  'inv',
  'pow',
  'ctrl',
  'negctrl',
  'dim',
  'durationof',
  'delay',
  'reset',
  'measure',
  'barrier',
  'true',
  'false',
  'pi',
  'tau',
  'euler',
  'im',
  'sizeof',
  // stdgates.inc gate names: shadowing one would change what a later call means.
  ...GATES.keys(),
  'sx',
  'cy',
  'cp',
  'crx',
  'cry',
  'crz',
  'ch',
  'cswap',
  'cu',
  'u1',
  'u2',
  'u3',
  'phase',
  'cphase',
  'U',
  'CX',
]);

export interface EmitQasmOptions {
  /** Emit `pi/2` style angles where exactly representable. Default true. */
  readonly prettyAngles?: boolean;
  /** Include the leading provenance comment block. Default true. */
  readonly header?: boolean;
  /** Include `; line N` style source comments. Default false. */
  readonly sourceComments?: boolean;
}

export interface EmitQasmResult {
  readonly code: string;
  /** QForge name -> emitted name, for every register that had to be renamed. */
  readonly renames: ReadonlyMap<string, string>;
}

function sanitize(name: string, taken: Set<string>): string {
  let candidate = QASM_RESERVED.has(name) ? `_${name}` : name;
  while (taken.has(candidate)) candidate = `_${candidate}`;
  taken.add(candidate);
  return candidate;
}

/**
 * Generate OpenQASM 3 source for `module`.
 *
 * Throws only if the module contains an opcode this backend does not know,
 * which cannot happen for a module produced by `lower()` — the check exists so
 * that adding an opcode without updating the backend fails loudly rather than
 * emitting silently wrong code.
 */
export function emitOpenQasm3(module: IrModule, options: EmitQasmOptions = {}): EmitQasmResult {
  const { prettyAngles = true, header = true, sourceComments = false } = options;

  const taken = new Set<string>();
  const renames = new Map<string, string>();
  const emittedName = new Map<string, string>();

  const register = (registers: readonly IrRegister[]): void => {
    for (const reg of registers) {
      const safe = sanitize(reg.name, taken);
      emittedName.set(`${reg.baseIndex}:${reg.name}`, safe);
      if (safe !== reg.name) renames.set(reg.name, safe);
    }
  };
  register(module.qubitRegisters);
  register(module.clbitRegisters);

  const nameOf = (reg: IrRegister): string =>
    emittedName.get(`${reg.baseIndex}:${reg.name}`) ?? reg.name;

  const operand = (registers: readonly IrRegister[], index: number, kind: string): string => {
    const found = resolveRegister(registers, index);
    if (!found) {
      throw new Error(`Internal error: ${kind} index ${index} belongs to no declared register`);
    }
    const base = nameOf(found.register);
    return found.register.isRegister ? `${base}[${found.offset}]` : base;
  };

  const qubit = (index: number): string => operand(module.qubitRegisters, index, 'qubit');
  const clbit = (index: number): string => operand(module.clbitRegisters, index, 'bit');

  const lines: string[] = [];

  if (header) {
    lines.push('// Generated by QForge. Supported subset only: see docs/limitations.md.');
    for (const [from, to] of renames) {
      lines.push(
        `// renamed '${from}' to '${to}': the original collides with an OpenQASM keyword`,
      );
    }
  }
  lines.push('OPENQASM 3.0;');
  lines.push('include "stdgates.inc";');
  lines.push('');

  for (const reg of module.qubitRegisters) {
    lines.push(reg.isRegister ? `qubit[${reg.size}] ${nameOf(reg)};` : `qubit ${nameOf(reg)};`);
  }
  for (const reg of module.clbitRegisters) {
    lines.push(reg.isRegister ? `bit[${reg.size}] ${nameOf(reg)};` : `bit ${nameOf(reg)};`);
  }
  if (module.qubitRegisters.length || module.clbitRegisters.length) lines.push('');

  for (const instruction of module.instructions) {
    let text: string;

    switch (instruction.opcode) {
      case Opcode.Measure:
        text = `${clbit(instruction.clbit ?? 0)} = measure ${qubit(instruction.qubits[0]!)};`;
        break;

      case Opcode.Reset:
        text = `reset ${qubit(instruction.qubits[0]!)};`;
        break;

      case Opcode.Barrier:
        text =
          instruction.qubits.length === 0
            ? `barrier ${module.qubitRegisters.map((r) => nameOf(r)).join(', ')};`
            : `barrier ${instruction.qubits.map(qubit).join(', ')};`;
        // A bare `barrier` with no declared qubits has nothing to fence.
        if (instruction.qubits.length === 0 && module.qubitRegisters.length === 0) continue;
        break;

      default: {
        const signature = GATES.get(instruction.opcode);
        if (!signature) {
          throw new Error(
            `Internal error: opcode '${instruction.opcode}' has no OpenQASM mapping`,
          );
        }
        const params = instruction.params.length
          ? `(${instruction.params.map((p) => formatAngle(p, prettyAngles)).join(', ')})`
          : '';
        text = `${signature.qasmName}${params} ${instruction.qubits.map(qubit).join(', ')};`;
        break;
      }
    }

    lines.push(sourceComments ? `${text}  // line ${instruction.loc.line}` : text);
  }

  return { code: `${lines.join('\n')}\n`, renames };
}
